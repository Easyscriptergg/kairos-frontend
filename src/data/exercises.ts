export function getExerciseById(id: string): Exercise | undefined {
  return exerciseLibrary.find(e => e.id === id);
}

export function getExercisesByBodyPart(bodyPart: string): Exercise[] {
  return exerciseLibrary.filter(e => e.bodyParts.includes(bodyPart as any));
}

export function getExercisesByMuscle(muscle: string): Exercise[] {
  return exerciseLibrary.filter(e =>
    e.primaryMuscles.includes(muscle as any) || e.secondaryMuscles.includes(muscle as any)
  );
}

export function getExercisesByMovementPattern(pattern: string): Exercise[] {
  return exerciseLibrary.filter(e => e.movementPattern === pattern);
}
